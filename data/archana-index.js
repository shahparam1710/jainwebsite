export function totalArchanaItems() {
  return archanaIndex.reduce((sum, s) => sum + s.items.length, 0);
}

export function transcribedArchanaItems() {
  return archanaIndex.reduce((sum, s) => sum + s.items.filter((i) => i.prayerId).length, 0);
}

export const archanaIndex = Object.entries(RAW).map(([section, rows]) => ({
  section,
  items: rows.map(([order, title, author, sourcePage]) => ({
    order,
    title,
    author,
    sourcePage,
    prayerId: TRANSCRIBED[`${section}:${order}`] || null,
  })),
}));

